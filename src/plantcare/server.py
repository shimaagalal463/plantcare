def serve(book_path: Path, host: str = "127.0.0.1", port: int = 8765) -> None:
    PlantcareHandler.book_path = Path(book_path)
    httpd = HTTPServer((host, port), PlantcareHandler)
    print("serving %s on http://%s:%d" % (book_path, host, port))
    httpd.serve_forever()


