"""Tiny read-only HTTP server for local viewing."""
from __future__ import annotations

import json
from http.server import BaseHTTPRequestHandler, HTTPServer
from pathlib import Path
from typing import Optional
from urllib.parse import urlparse

from .reports import summary_report
from .storage import Book


class PlantcareHandler(BaseHTTPRequestHandler):
    book_path: Optional[Path] = None

    def do_GET(self) -> None:
        parsed = urlparse(self.path)
        if parsed.path == "/summary":
            book = Book.load(self.book_path)
            body = summary_report(book).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "text/plain; charset=utf-8")
            self.end_headers()
            self.wfile.write(body)
        elif parsed.path == "/json":
            book = Book.load(self.book_path)
            body = json.dumps(book.to_dict()).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(body)
        else:
            self.send_response(404)
            self.end_headers()

    def log_message(self, fmt, *args):
        pass


