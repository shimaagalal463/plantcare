"""Light level vocabulary."""
from __future__ import annotations

from typing import Dict, List

LIGHT_LEVELS = ["low", "medium", "bright-indirect", "bright-direct", "full-sun"]


def normalize_light_level(raw: str) -> str:
    s = (raw or "").strip().lower()
    if not s:
        return "medium"
    for level in LIGHT_LEVELS:
        if level in s or s in level:
            return level
    return s


def light_label(code: str) -> str:
    return code.replace("-", " ").title() if code else "unspecified"


def count_by_light(rooms: list) -> Dict[str, int]:
    tallies: Dict[str, int] = {}
    for r in rooms:
        key = normalize_light_level(getattr(r, "light_level", "") or "medium")
        tallies[key] = tallies.get(key, 0) + 1
    return tallies


