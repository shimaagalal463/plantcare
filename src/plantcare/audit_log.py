"""Append-only audit trail."""
from __future__ import annotations

from dataclasses import dataclass, asdict
from datetime import datetime
from typing import Any, Dict, TYPE_CHECKING

if TYPE_CHECKING:
    from .storage import Book


@dataclass
class AuditEntry:
    action: str
    timestamp: str
    details: Dict[str, Any]

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "AuditEntry":
        return cls(action=data["action"], timestamp=data["timestamp"], details=dict(data.get("details", {})))


def log_action(book: "Book", action: str, details: Dict[str, Any] | None = None) -> None:
    entry = AuditEntry(action=action, timestamp=datetime.utcnow().isoformat(timespec="seconds"), details=details or {})
    book.audit_log.append(entry)


def recent_actions(book: "Book", limit: int = 20) -> list:
    return book.audit_log[-limit:]


