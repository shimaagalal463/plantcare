"""Minimal plugin loader."""
from __future__ import annotations

import importlib.util
from pathlib import Path
from typing import Any, Callable, Dict, List

from .errors import PluginError

_hooks: Dict[str, List[Callable]] = {"report": [], "import": []}


def register_hook(name: str, fn: Callable) -> None:
    _hooks.setdefault(name, []).append(fn)


def run_hooks(name: str, *args, **kwargs) -> List[Any]:
    return [fn(*args, **kwargs) for fn in _hooks.get(name, [])]


def load_plugin(path: Path) -> None:
    if not path.exists():
        raise PluginError("missing plugin %s" % path)
    spec = importlib.util.spec_from_file_location(path.stem, path)
    if spec is None or spec.loader is None:
        raise PluginError("bad plugin %s" % path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    if hasattr(mod, "register"):
        mod.register(register_hook)


