"""Soil moisture helpers."""
from __future__ import annotations

from typing import Dict

MOISTURE_LEVELS = ["dry", "slightly-dry", "moist", "wet", "soggy"]


def normalize_moisture(raw: str) -> str:
    s = (raw or "").strip().lower()
    if not s:
        return ""
    for m in MOISTURE_LEVELS:
        if m in s or s in m:
            return m
    return s


def moisture_label(code: str) -> str:
    return code.replace("-", " ").title() if code else "unspecified"


def count_by_moisture(care_logs: list) -> Dict[str, int]:
    tallies: Dict[str, int] = {}
    for c in care_logs:
        h = normalize_moisture(getattr(c, "soil_moisture", "") or "unknown")
        tallies[h or "unknown"] = tallies.get(h or "unknown", 0) + 1
    return tallies


