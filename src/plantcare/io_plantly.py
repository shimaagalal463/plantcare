"""Import Plantly app CSV export."""
from __future__ import annotations

import csv
from pathlib import Path
from typing import TYPE_CHECKING

from .care_log import CareLog
from .plant import Plant

if TYPE_CHECKING:
    from .storage import Book


def import_plantly_csv(book: "Book", path: Path) -> int:
    n = 0
    with path.open(newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            name = row.get("plant_name") or row.get("name") or "Unknown"
            plant = Plant(name=name, species=row.get("species", ""))
            book.add_plant(plant)
            book.add_care_log(CareLog(
                plant_id=plant.id,
                action=row.get("action", "water"),
                performed_at=(row.get("date") or "2024-06-01") + "T10:00:00",
                notes=row.get("notes", ""),
            ))
            n += 1
    return n


