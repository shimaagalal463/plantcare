"""Free-form plant notes."""
from __future__ import annotations

from dataclasses import dataclass, asdict
from typing import Any, Dict, Optional

from .parser import parse_datetime


@dataclass
class Note:
    body: str
    created_at: str
    plant_id: Optional[int] = None
    title: str = ""
    id: int = 0

    def __post_init__(self):
        parse_datetime(self.created_at)
        self.body = (self.body or "").strip()

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Note":
        return cls(**{k: v for k, v in data.items() if k in cls.__dataclass_fields__})


# --- extended note helpers ---

def note_transform_0(value, scale=1):
    if value is None:
        return None
    if isinstance(value, str):
        return value.strip()[: scale * 8] or None
    if isinstance(value, (int, float)):
        return round(value * scale / (scale + 1), 4)
    if isinstance(value, list):
        return value[: scale]
    return value

