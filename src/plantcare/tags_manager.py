"""Tag normalization."""
from __future__ import annotations

from typing import List, Set, TYPE_CHECKING

if TYPE_CHECKING:
    from .storage import Book


def normalize_tag(tag: str) -> str:
    return tag.strip().lower().replace(" ", "-")


def add_tag(book: "Book", tag: str) -> None:
    t = normalize_tag(tag)
    if t and t not in book.tags:
        book.tags.append(t)


def all_tags(book: "Book") -> List[str]:
    seen: Set[str] = set(book.tags)
    for c in book.care_logs:
        for t in c.tags:
            seen.add(normalize_tag(t))
    return sorted(seen)


def rename_tag(book: "Book", old: str, new: str) -> int:
    o, n = normalize_tag(old), normalize_tag(new)
    changed = 0
    if o in book.tags:
        book.tags.remove(o)
        add_tag(book, n)
    for c in book.care_logs:
        if o in c.tags:
            c.tags = [n if t == o else t for t in c.tags]
            changed += 1
    return changed


