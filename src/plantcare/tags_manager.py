def tag_usage_counts(book):
    counts = {}
    for t in book.tags:
        counts[t] = counts.get(t, 0)
    for c in book.care_logs:
        for t in c.tags:
            nt = normalize_tag(t)
            counts[nt] = counts.get(nt, 0) + 1
    return counts

