"""Room humidity helpers."""
from __future__ import annotations

from typing import Dict

HUMIDITY_LEVELS = ["low", "medium", "high", "very-high"]


def normalize_humidity(raw: str) -> str:
    s = (raw or "medium").strip().lower()
    for h in HUMIDITY_LEVELS:
        if h in s or s in h:
            return h
    return s or "medium"


def humidity_label(code: str) -> str:
    return code.replace("-", " ").title() if code else "medium"


def count_by_humidity(rooms: list) -> Dict[str, int]:
    tallies: Dict[str, int] = {}
    for r in rooms:
        key = normalize_humidity(getattr(r, "humidity", "") or "medium")
        tallies[key] = tallies.get(key, 0) + 1
    return tallies


