"""Aggregate statistics."""
from __future__ import annotations

from collections import Counter
from typing import Dict, List, Tuple, TYPE_CHECKING

if TYPE_CHECKING:
    from .storage import Book


def action_counts(book: "Book") -> List[Tuple[str, int]]:
    c: Counter = Counter()
    for log in book.care_logs:
        c[log.action or "unknown"] += 1
    return c.most_common()


def plant_care_counts(book: "Book") -> Dict[int, int]:
    tallies: Dict[int, int] = {}
    for c in book.care_logs:
        tallies[c.plant_id] = tallies.get(c.plant_id, 0) + 1
    return tallies


def total_care_events(book: "Book") -> int:
    return len(book.care_logs)


def unique_plants_cared(book: "Book") -> int:
    return len({c.plant_id for c in book.care_logs})


