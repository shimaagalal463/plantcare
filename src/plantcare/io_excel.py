"""Minimal XLSX export via zip+xml — no openpyxl."""
from __future__ import annotations

import zipfile
from pathlib import Path
from typing import TYPE_CHECKING
from xml.sax.saxutils import escape

if TYPE_CHECKING:
    from .storage import Book

_SHEET = """<?xml version="1.0"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>{rows}</sheetData></worksheet>"""


def _cell(r, c, val):
    col = chr(ord("A") + c)
    return f'<c r="{col}{r}" t="inlineStr"><is><t>{escape(str(val))}</t></is></c>'


def export_rooms_xlsx(book: "Book", dest: Path) -> None:
    rows = []
    for i, room in enumerate(book.rooms, start=1):
        cells = "".join(_cell(i, j, v) for j, v in enumerate([room.id, room.name, room.light_level, room.humidity]))
        rows.append(f'<row r="{i}">{cells}</row>')
    sheet = _SHEET.format(rows="".join(rows))
    with zipfile.ZipFile(dest, "w") as zf:
        zf.writestr("[Content_Types].xml", '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"></Types>')
        zf.writestr("xl/worksheets/sheet1.xml", sheet)


