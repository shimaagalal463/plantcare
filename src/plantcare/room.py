def rooms_by_light(rooms, level):
    key = (level or "").lower()
    return [r for r in rooms if key in (r.light_level or "").lower()]


def find_room_by_name(rooms, name):
    key = name.lower()
    for room in rooms:
        if room.name.lower() == key:
            return room
    return None

