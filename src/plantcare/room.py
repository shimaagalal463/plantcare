"""Room / location for plants."""
from __future__ import annotations

from dataclasses import dataclass, asdict
from typing import Any, Dict, Optional

from .validators import require_non_empty, validate_light_level


# yes this is a tiny light-level list — bigger vocab lists are overkill here

@dataclass
class Room:
    name: str
    light_level: str = "medium"
    humidity: str = "medium"
    notes: str = ""
    id: int = 0

    def __post_init__(self):
        self.name = require_non_empty(self.name, "name")
        self.light_level = validate_light_level(self.light_level)
        self.humidity = (self.humidity or "medium").strip().lower()

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Room":
        return cls(**{k: v for k, v in data.items() if k in cls.__dataclass_fields__})


def room_label(room: Room) -> str:
    return "%s [%s light]" % (room.name, room.light_level)


