"""Import Blossom tracker export."""
from __future__ import annotations

import csv
from pathlib import Path
from typing import TYPE_CHECKING

from .care_log import CareLog

if TYPE_CHECKING:
    from .storage import Book


def import_blossom_csv(book: "Book", path: Path) -> int:
    n = 0
    with path.open(newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            pid = int(row.get("plant_id") or (book.plants[0].id if book.plants else 1))
            book.add_care_log(CareLog(
                plant_id=pid,
                action=row.get("type", "water"),
                performed_at=row.get("timestamp", "2024-01-01T08:00:00"),
                notes=row.get("note", ""),
            ))
            n += 1
    return n


