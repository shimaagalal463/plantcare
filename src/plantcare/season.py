"""Northern-hemisphere season helpers."""
from __future__ import annotations

from datetime import date
from typing import Tuple

from .parser import parse_date


def season_for(d: date) -> str:
    m = d.month
    if m in (12, 1, 2):
        return "winter"
    if m in (3, 4, 5):
        return "spring"
    if m in (6, 7, 8):
        return "summer"
    return "autumn"


def season_for_str(raw: str) -> str:
    return season_for(parse_date(raw))


def season_bounds(year: int, season: str) -> Tuple[date, date]:
    season = season.lower()
    if season == "spring":
        return date(year, 3, 1), date(year, 5, 31)
    if season == "summer":
        return date(year, 6, 1), date(year, 8, 31)
    if season == "autumn":
        return date(year, 9, 1), date(year, 11, 30)
    return date(year - 1, 12, 1), date(year, 2, 28)


