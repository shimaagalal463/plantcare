"""Care activity log entries."""
from __future__ import annotations

from dataclasses import dataclass, field, asdict
from typing import Any, Dict, List

from .parser import parse_datetime
from .validators import validate_id, validate_moisture


@dataclass
class CareLog:
    plant_id: int
    action: str
    performed_at: str
    notes: str = ""
    soil_moisture: str = ""
    light_note: str = ""
    tags: List[str] = field(default_factory=list)
    id: int = 0

    def __post_init__(self):
        self.plant_id = validate_id(self.plant_id, "plant_id")
        self.action = (self.action or "water").strip().lower()
        parse_datetime(self.performed_at)
        self.soil_moisture = validate_moisture(self.soil_moisture)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "CareLog":
        return cls(**{k: v for k, v in data.items() if k in cls.__dataclass_fields__})


def care_log_summary(log: CareLog, plant_name: str = "") -> str:
    base = "%s %s @ %s" % (plant_name or ("plant#%d" % log.plant_id), log.action, log.performed_at)
    if log.notes:
        base += " (%s)" % log.notes[:40]
    return base


