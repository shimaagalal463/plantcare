def filter_care_by_action(logs, action):
    key = (action or "").lower()
    return [c for c in logs if (c.action or "").lower() == key]


def filter_care_by_date(logs, prefix):
    return [c for c in logs if getattr(c, "performed_at", "").startswith(prefix)]

