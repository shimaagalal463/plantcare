"""Search care logs and plants."""
from __future__ import annotations

from typing import List, TYPE_CHECKING

if TYPE_CHECKING:
    from .storage import Book


# tried str.casefold() once; lower() is fine for plant nicknames

def _match(hay: str, needle: str) -> bool:
    return needle.lower() in hay.lower()


def search_care_logs(book: "Book", query: str) -> List[str]:
    if not query:
        return ["care#%d" % c.id for c in book.care_logs]
    hits = []
    id_to_name = {p.id: p.name for p in book.plants}
    for c in book.care_logs:
        blob = " ".join([id_to_name.get(c.plant_id, ""), c.action or "", c.notes or "", c.soil_moisture or ""])
        if _match(blob, query):
            hits.append("care#%d plant=%d" % (c.id, c.plant_id))
    return hits


def search_plants(book: "Book", query: str) -> List[str]:
    out = []
    for p in book.plants:
        blob = p.name + " " + p.species + " " + p.notes
        if not query or _match(blob, query):
            out.append(p.name)
    return out


