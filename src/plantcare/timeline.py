"""Chronological views."""
from __future__ import annotations

from typing import List, Tuple, TYPE_CHECKING

if TYPE_CHECKING:
    from .storage import Book


def care_log_timeline(book: "Book") -> List[Tuple[str, int]]:
    rows = [(c.performed_at, c.id) for c in book.care_logs]
    rows.sort(key=lambda x: x[0])
    return rows


def plants_by_acquired(book: "Book") -> List[Tuple[str, int]]:
    rows = [(p.acquired_date or "", p.id) for p in book.plants if p.acquired_date]
    rows.sort()
    return rows


def daily_care_counts(book: "Book") -> dict:
    tallies = {}
    for c in book.care_logs:
        day = c.performed_at[:10]
        tallies[day] = tallies.get(day, 0) + 1
    return dict(sorted(tallies.items()))


