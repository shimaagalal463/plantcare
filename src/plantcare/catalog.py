"""Plant catalog operations."""
from __future__ import annotations

from typing import Dict, Optional, TYPE_CHECKING

from .plant import Plant

if TYPE_CHECKING:
    from .storage import Book


def index_plants(book: "Book") -> Dict[str, Plant]:
    return {p.name.lower(): p for p in book.plants}


def find_plant_by_name(book: "Book", name: str) -> Optional[Plant]:
    key = name.lower().strip()
    for p in book.plants:
        if p.name.lower() == key:
            return p
    return None


